import { ACTION_PINS } from "./advisory/index.js";
import { existsSync, writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";
import { VERSION } from "./engine.js";

/**
 * init-ci (Plan v0.2): generates a least-privilege GitHub Actions workflow that
 * runs the scan on every PR/push and uploads SARIF to the Security tab, with
 * --fail-on critical so a PR containing a critical finding is BLOCKED.
 * All third-party actions are pinned to real commit SHAs (v1.6 CI-001 applies
 * to our own output — a generator that emits unpinned actions would be absurd).
 */
export function generateWorkflow(dir: string, opts: { packageManager?: string } = {}): { file: string; created: boolean } {
  const wfDir = join(dir, ".github", "workflows");
  const file = join(wfDir, "anubis-guardian.yml");
  if (existsSync(file)) return { file, created: false };

  const pm = opts.packageManager ?? "npm";
  const tool = `anubis-guardian@${VERSION}`; // pinned — never @latest (v1.6 CI-001 discipline applies to our own output)
  const runScan = pm === "pnpm" ? `pnpm dlx ${tool} scan . --format sarif --output results.sarif --fail-on critical` : pm === "yarn" ? `yarn dlx ${tool} scan . --format sarif --output results.sarif --fail-on critical` : `npx --yes ${tool} scan . --format sarif --output results.sarif --fail-on critical`;

  const yml = `# Generated by anubis-guardian init-ci — deterministic security gate.
# A PR that introduces a CRITICAL finding FAILS this workflow (blocked from merge).
# SARIF results upload to the GitHub Security tab (code scanning).
name: Anubis Guardian Security Audit

on:
  pull_request:
  push:
    branches: [main]

permissions:
  contents: read
  security-events: write

jobs:
  security-audit:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@${ACTION_PINS.pins["actions/checkout"]} # v4
        with:
          fetch-depth: 0   # full history — the audit scans git history for leaked secrets
      - uses: actions/setup-node@${ACTION_PINS.pins["actions/setup-node"]} # v4
        with:
          node-version: 20
      - name: Anubis Guardian scan (deterministic, offline)
        run: ${runScan}
      - name: Upload SARIF to the Security tab
        if: always()
        uses: github/codeql-action/upload-sarif@${ACTION_PINS.pins["github/codeql-action"]}
        with:
          sarif_file: results.sarif
`;

  mkdirSync(wfDir, { recursive: true });
  writeFileSync(file, yml, "utf8");
  return { file, created: true };
}
