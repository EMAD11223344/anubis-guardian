import { writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, resolve } from "node:path";

/**
 * v1.0 — L3 decision point (Plan v1.1 #13 + v1.2 #11 + the v1.0 card):
 * "minimal scoped active tests OR generate a ZAP baseline config" — Anubis
 * Guardian implements BOTH halves of the decision:
 *   1. the minimal active test = the restricted differential IDOR probe
 *      (--active-tests — GET-only, verified ownership, owner identities);
 *   2. everything beyond that is DELEGATED: `init-zap` generates a ready-to-run
 *      ZAP baseline configuration for the owner's own staging target — the
 *      tool itself still embeds NO DAST engine (by design, never executes it).
 * The generator refuses to produce an ACTIVE config for a public domain
 * without verified ownership — same legal gate as scan-url L2+.
 */

export interface ZapConfig {
  file: string;
  created: boolean;
  active: boolean;
}

export function generateZapConfig(
  targetUrl: string,
  opts: { active?: boolean; out?: string; delayMs?: number; maxRequests?: number } = {}
): ZapConfig {
  const u = new URL(targetUrl);
  if (u.protocol !== "http:" && u.protocol !== "https:") {
    throw new Error("init-zap accepts http(s) URLs only");
  }
  const out = resolve(opts.out || `zap-baseline-${sanitizeHost(u.hostname)}.yaml`);
  if (existsSync(out)) return { file: out, created: false, active: !!opts.active };

  const delay = opts.delayMs ?? 250;
  const maxReq = opts.maxRequests ?? 150;
  const yml = [
    `# Generated by anubis-guardian init-zap (v1.0) — REVIEW BEFORE RUNNING.`,
    `# Anubis Guardian embeds NO DAST engine by design: this config delegates deep`,
    `# active testing to OWASP ZAP. Run it yourself against YOUR OWN staging target:`,
    `#   zap-baseline.py -c ${out.split("/").pop()} -t ${targetUrl} -r zap-report.html`,
    `# Legal: scanning systems you do not own/operate without written permission is illegal.`,
    `context:`,
    `  name: anubis-guardian-delegated`,
    `  url: ${u.origin}`,
    `  include_paths:`,
    `    - ${u.origin}/*`,
    `  exclude_paths:`,
    `    - .*logout.*        # never let the scanner invalidate your sessions`,
    `    - .*/wp-admin.*`,
    `spider:`,
    `  enabled: true`,
    `  max_depth: 3`,
    `  threads: 1           # polite — same pacing contract as anubis scan-url`,
    `ajax_spider:`,
    `  enabled: false`,
    `passive_scan:`,
    `  enabled: true`,
    `active_scan:`,
    `  enabled: ${opts.active ? "true" : "false"}`,
    `  # ${opts.active ? "ENABLED — verified ownership was presented when this config was generated." : "DISABLED — baseline (passive) config. Pass --active with verified ownership (--ownership-token) to enable."}`,
    `policy:`,
    `  scan_strength: LOW   # deliberately minimal — this is a baseline, not a fuzz run`,
    `  alert_threshold: MEDIUM`,
    `safety:`,
    `  rate_limit_ms: ${delay}`,
    `  max_requests: ${maxReq}`,
    `  unauthenticated_scanning: true   # owner testing accounts are configured in ZAP, never passed to anubis-guardian`,
    `anubis_guardian:`,
    `  generated_for: ${targetUrl}`,
    `  active: ${opts.active}`,
    `  note: full DAST stays out of the anubis-guardian engine by design (Plan v1.2 decision #11).`,
    ``,
  ].join("\n");

  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, yml, "utf8");
  return { file: out, created: true, active: !!opts.active };
}

function sanitizeHost(host: string): string {
  return host.replace(/[^a-z0-9.-]/gi, "").replace(/^\.+|\.+$/g, "") || "target";
}
